/**
 * Helper to resolve manager information by team ID or team display name
 */
export function getTeamManagerInfo(teamIdentifier) {
  if (!teamIdentifier) return null;
  const idStr = String(teamIdentifier);
  if (PREMIER_LEAGUE_MANAGERS[idStr]) {
    return PREMIER_LEAGUE_MANAGERS[idStr];
  }

  const normalised = idStr.toLowerCase().replace(/[^a-z0-9]/g, "");
  for (const info of Object.values(PREMIER_LEAGUE_MANAGERS)) {
    const clubNorm = info.name.toLowerCase().replace(/[^a-z0-9]/g, "");
    if (clubNorm.includes(normalised) || normalised.includes(clubNorm)) {
      return info;
    }
  }

  if (normalised.includes("manchesterunited") || normalised.includes("manunited") || normalised.includes("manutd")) {
    return PREMIER_LEAGUE_MANAGERS["360"];
  }
  if (normalised.includes("manchestercity") || normalised.includes("mancity")) {
    return PREMIER_LEAGUE_MANAGERS["382"];
  }
  if (normalised.includes("brighton")) {
    return PREMIER_LEAGUE_MANAGERS["331"];
  }
  if (normalised.includes("tottenham") || normalised.includes("spurs")) {
    return PREMIER_LEAGUE_MANAGERS["367"];
  }
  if (normalised.includes("bournemouth")) {
    return PREMIER_LEAGUE_MANAGERS["349"];
  }
  if (normalised.includes("newcastle")) {
    return PREMIER_LEAGUE_MANAGERS["361"];
  }
  if (normalised.includes("nottingham")) {
    return PREMIER_LEAGUE_MANAGERS["393"];
  }

  // Tier-2 lookup for UEFA Champions League / Europa League / Conference League rivals
  const euroClub = getEuropeanClubInfo(teamIdentifier);
  if (euroClub) {
    return euroClub;
  }

  return null;
}
